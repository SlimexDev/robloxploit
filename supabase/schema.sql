CREATE TABLE IF NOT EXISTS admins (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username VARCHAR(80) NOT NULL UNIQUE,
  password_hash VARCHAR(200) NOT NULL
);
CREATE TABLE IF NOT EXISTS scripts (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title VARCHAR(160) NOT NULL,
  game VARCHAR(100) NOT NULL,
  description TEXT NOT NULL,
  code TEXT NOT NULL,
  script_url VARCHAR(2000),
  tasks_json TEXT,
  image VARCHAR(2048) NOT NULL,
  published SMALLINT NOT NULL DEFAULT 0 CHECK (published IN (0, 1)),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS public_feed ON scripts (published, created_at DESC);
CREATE INDEX IF NOT EXISTS game_filter ON scripts (game);
CREATE TABLE IF NOT EXISTS settings (
  id INTEGER PRIMARY KEY CHECK (id = 1),
  channel_url VARCHAR(500) NOT NULL,
  video_url VARCHAR(500) NOT NULL,
  combined SMALLINT NOT NULL DEFAULT 1 CHECK (combined IN (0, 1)),
  wait_seconds INTEGER NOT NULL DEFAULT 7 CHECK (wait_seconds BETWEEN 1 AND 120)
);
CREATE TABLE IF NOT EXISTS app_sessions (
  id VARCHAR(64) PRIMARY KEY,
  data JSONB NOT NULL,
  expires_at TIMESTAMPTZ NOT NULL
);
